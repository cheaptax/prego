import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appDirectory = path.join(root, "app");
const outputPath = path.join(
  root,
  "lib",
  "sitemap",
  "generated-app-pages.ts",
);

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolutePath = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(absolutePath) : [absolutePath];
  });
}

function routeFromPage(pagePath) {
  const relative = path.relative(appDirectory, pagePath).replaceAll("\\", "/");
  const segments = relative
    .split("/")
    .slice(0, -1)
    .filter(
      (segment) =>
        segment &&
        !(segment.startsWith("(") && segment.endsWith(")")) &&
        !segment.startsWith("@"),
    );
  return segments.length ? `/${segments.join("/")}` : "/";
}

function audienceForRoute(route) {
  if (route === "/partner/apply") return "public";
  if (route === "/admin" || route.startsWith("/admin/")) return "admin";
  if (route === "/mypage" || route.startsWith("/mypage/")) return "customer";
  if (route === "/partner" || route.startsWith("/partner/")) return "partner";
  return "public";
}

const pages = walk(appDirectory)
  .filter((filePath) => /[/\\]page\.(?:js|jsx|ts|tsx)$/u.test(filePath))
  .map((filePath) => {
    const route = routeFromPage(filePath);
    return {
      route,
      audience: audienceForRoute(route),
      dynamic: route.includes("["),
      sourcePath: path.relative(root, filePath).replaceAll("\\", "/"),
    };
  })
  .sort(
    (left, right) =>
      left.route.localeCompare(right.route) ||
      left.sourcePath.localeCompare(right.sourcePath),
  );

const duplicateRoutes = pages.filter(
  (page, index) => pages.findIndex((candidate) => candidate.route === page.route) !== index,
);
if (duplicateRoutes.length) {
  throw new Error(
    `duplicate_page_routes:${duplicateRoutes.map((page) => page.route).join(",")}`,
  );
}

const output = `// This file is generated by scripts/generate-portal-sitemap.mjs.
// Do not edit it manually. It is refreshed before dev, typecheck, and build.

export type GeneratedPortalAudience =
  | "public"
  | "customer"
  | "partner"
  | "admin";

export type GeneratedAppPage = {
  route: string;
  audience: GeneratedPortalAudience;
  dynamic: boolean;
  sourcePath: string;
};

export const GENERATED_APP_PAGES = ${JSON.stringify(pages, null, 2)} as const satisfies readonly GeneratedAppPage[];
`;

mkdirSync(path.dirname(outputPath), { recursive: true });
const previous = existsSync(outputPath)
  ? await import("node:fs/promises").then(({ readFile }) =>
      readFile(outputPath, "utf8"),
    )
  : "";
if (previous !== output) {
  writeFileSync(outputPath, output, "utf8");
}

console.log(`portal-sitemap-generated:${pages.length}`);
