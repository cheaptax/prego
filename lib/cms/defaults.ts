type SectionInput = Omit<
  CmsSection,
  | "visible"
  | "locked"
  | "headingLevel"
  | "text"
  | "items"
  | "actions"
  | "groups"
  | "style"
> & {
  visible?: boolean;
  locked?: boolean;
  headingLevel?: CmsSection["headingLevel"];
  text?: CmsSection["text"];
  items?: CmsSection["items"];
  actions?: CmsLink[];
  groups?: CmsSection["groups"];
  style?: CmsSection["style"];
};

const action = (
  id: string,
  label: string,
  href: string,
  appearance: CmsLink["appearance"] = "primary",
): CmsLink => ({
  id,
  label,
  href,
  linkType: "internal",
  appearance,
  openInNewWindow: false,
});

const section = (input: SectionInput): CmsSection => ({
  visible: true,
  locked: false,
  headingLevel: 2,
  text: {},
  items: [],
  actions: [],
  groups: [],
  style: {
    title: {
      fontFamily: "pretendard",
      sizePreset: "default",
      fontWeight: "700",
      lineHeightPreset: "default",
      alignment: "left",
      color: "text",
    },
    body: {
      fontFamily: "pretendard",
      sizePreset: "default",
      fontWeight: "400",
      lineHeightPreset: "default",
      alignment: "left",
      color: "muted",
    },
    container: {
      background: "surface",
      spacing: "default",
      border: "none",
      radius: "default",
      shadow: "none",
    },
  },
  ...input,
});

const item = (
  id: string,
  title: string,
  description?: string,
  value?: string,
): CmsSection["items"][number] => ({
  id,
  title,
  description,
  value,
  visible: true,
  deleted: false,
});

const group = (
  id: string,
  input: Omit<CmsContentGroup, "id" | "visible" | "items" | "actions"> & {
    visible?: boolean;
    items?: CmsContentGroup["items"];
    actions?: CmsContentGroup["actions"];
  } = {},
): CmsContentGroup => ({
  id,
  visible: true,
  items: [],
  actions: [],
  ...input,
});

const page = (
  title: string,
  description: string,
  sections: CmsSection[],
  messages: CmsPageContent["messages"] = {},
): CmsPageContent => ({
  seo: { title, description, indexable: true },
  sections,
  messages,
});

