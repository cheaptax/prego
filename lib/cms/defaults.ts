export function validatePageIdentity(
  pageKey: CmsPageKey,
  route: string,
  content: CmsPageContent,
) {
  if (route !== CMS_PAGE_ROUTES[pageKey]) {
    return { success: false as const, reason: "route_mismatch" as const };
  }
  const sectionIds = new Set(content.sections.map(({ id }) => id));
  const missingRequiredSection = CMS_REQUIRED_PAGE_SECTIONS[pageKey].find(
    (sectionId) => !sectionIds.has(sectionId),
  );
  if (missingRequiredSection) {
    return {
      success: false as const,
      reason: "required_section_missing" as const,
      sectionId: missingRequiredSection,
    };
  }
  const invalidRequiredSection = CMS_REQUIRED_PAGE_SECTIONS[pageKey].find(
    (sectionId) => {
      const section = content.sections.find(
        (candidate) => candidate.id === sectionId,
      );
      return !section?.visible || !section.locked;
    },
  );
  if (invalidRequiredSection) {
    return {
      success: false as const,
      reason: "required_section_unlocked_or_hidden" as const,
      sectionId: invalidRequiredSection,
    };
  }
  return { success: true as const };
}
